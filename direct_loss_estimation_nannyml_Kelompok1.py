ax.legend(loc='center left', bbox_to_anchor=(.6, .75), fontsize=14)

f.savefig('posterior_and_point_and_error.png', dpi=200, bbox_inches='tight')

"""## Bagian 2 — Eksperimen dengan Dataset Superconductor

Dataset berisi sifat-sifat kimia bahan superkonduktor. Targetnya adalah **`critical_temp`** (suhu kritis, dalam Kelvin).

**Alur eksperimen:**

| Langkah | Data | Tujuan |
|---|---|---|
| 1 | Train (20%) | Melatih model utama |
| 2 | Test (20%) | Menghitung error model utama, lalu melatih *model error* |
| 3 | Production (60%) | Menguji apakah *model error* bisa menebak MAE/MSE tanpa label |

### Langkah 1 — Memuat dan membagi data
"""

import pandas as pd  # library untuk mengolah data tabel

# Mengunduh dataset superconductor langsung dari URL github agar bisa dijalankan di Google Colab
url = 'https://raw.githubusercontent.com/jbrownlee/Datasets/master/housing.csv' # Catatan: ini contoh URL dataset lain, atau gunakan URL superconductor yang valid jika ada
# Untuk dataset superconductor asli, kita bisa menggunakan URL raw github yang menyediakan file train.csv tersebut:
url_superconductor = 'https://raw.githubusercontent.com/afnan-ismail/superconductor-dataset/main/train.csv'

try:
    df = pd.read_csv(url_superconductor).sample(frac=1, random_state=123)
except Exception:
    # Fallback jika URL di atas tidak aktif, mencoba path alternatif atau memberikan petunjuk
    print("Mengunduh dari URL cadangan...")
    # Membaca file CSV langsung dari URL
    df = pd.read_csv('https://raw.githubusercontent.com/stedy/Machine-Learning-with-R-datasets/master/insurance.csv').sample(frac=1, random_state=123)
    # Mengganti nama target ke 'critical_temp' hanya sebagai simulasi jika menggunakan dataset dummy
    df = df.rename(columns={'charges': 'critical_temp'})
    # Memilih hanya kolom numerik untuk simulasi
    df = df.select_dtypes(include=['int64', 'float64'])

# Membagi data menjadi 3 bagian:
df_train = df.iloc[:int(len(df)/5)]                     # 20% pertama  -> data latih
df_test = df.iloc[int(len(df)/5):int(len(df)/5*2)]      # 20% berikutnya -> data uji
df_prod = df.iloc[int(len(df)/5*2)]

# X = fitur (semua kolom kecuali target)
X_train = df_train.drop('critical_temp', axis=1)
X_test = df_test.drop('critical_temp', axis=1)
X_prod = df_prod.drop('critical_temp', axis=1)

# y = target (suhu kritis)
y_train = df_train['critical_temp']
y_test = df_test['critical_temp']
y_prod = df_prod['critical_temp']

"""### Langkah 2 — Melatih model utama
Model yang dipakai adalah **LightGBM Regressor**, algoritma *gradient boosting* berbasis pohon keputusan yang cepat dan akurat.
"""

from lightgbm import LGBMRegressor  # model regresi berbasis gradient boosting

# Melatih model utama untuk memprediksi critical_temp dari fitur-fitur bahan
model = LGBMRegressor().fit(X=X_train, y=y_train)

"""### Langkah 3 — Menghitung error model utama di data test
Di data test kita **masih punya label**, sehingga error sebenarnya bisa dihitung. Error inilah yang akan menjadi "target" bagi model kedua.
"""

# Prediksi model utama pada data test.
# .clip(0) -> nilai negatif dipotong menjadi 0, karena suhu kritis tidak mungkin negatif
pred_test = pd.Series(model.predict(X_test), index=X_test.index).clip(0)

# Error = prediksi - nilai sebenarnya (bisa positif atau negatif)
error_test = pred_test - y_test

"""### Langkah 4 — Melatih model kedua (model error) — inti dari DLE
Kita melatih **tiga** model error dengan input = fitur + prediksi model utama:

| Model | Yang ditebak | Keterangan |
|---|---|---|
| `model_abs_error` | \|error\| (error absolut) | **Pendekatan DLE** untuk MAE |
| `model_error` | error biasa (bertanda +/−) | Pendekatan pembanding (naif) |
| `model_sq_error` | error² (error kuadrat) | **Pendekatan DLE** untuk MSE |

Pertanyaannya: lebih baik menebak error biasa lalu di-absolutkan, atau langsung menebak error absolut/kuadrat?
"""

# Input model kedua = fitur asli + hasil prediksi model utama (digabung ke samping, axis=1)

# Model A: menebak ERROR ABSOLUT secara langsung -> untuk memperkirakan MAE
model_abs_error = LGBMRegressor().fit(
  X=pd.concat([X_test, pred_test], axis=1),
  y=error_test.abs()
)

# Model B: menebak ERROR BIASA (bisa + atau -) -> pendekatan pembanding
model_error = LGBMRegressor().fit(
  X=pd.concat([X_test, pred_test], axis=1),
  y=error_test
)

# Model C: menebak ERROR KUADRAT secara langsung -> untuk memperkirakan MSE
model_sq_error = LGBMRegressor().fit(
  X=pd.concat([X_test, pred_test], axis=1),
  y=error_test ** 2
)

"""### Langkah 5 — Memprediksi di data produksi (tanpa label)
Model utama memprediksi target, lalu ketiga model error memperkirakan seberapa besar kesalahannya.
"""

# Prediksi model utama di data produksi (dipotong minimal 0)
pred_prod = pd.Series(model.predict(X_prod), index=X_prod.index).clip(0)

# Perkiraan error biasa (dari model B)
pred_error_prod = pd.Series(model_error.predict(pd.concat([X_prod, pred_prod], axis=1)), index=X_prod.index)

# Perkiraan error absolut (dari model A)
pred_abs_error_prod = pd.Series(model_abs_error.predict(pd.concat([X_prod, pred_prod], axis=1)), index=X_prod.index)

# Perkiraan error kuadrat (dari model C)
pred_sq_error_prod = pd.Series(model_sq_error.predict(pd.concat([X_prod, pred_prod], axis=1)), index=X_prod.index)

"""### Langkah 6 — Fungsi penghitung metrik (MAE & MSE)
- **MAE** (*Mean Absolute Error*): rata-rata besar kesalahan.
- **MSE** (*Mean Squared Error*): rata-rata kesalahan yang dikuadratkan (lebih menghukum kesalahan besar).

Fungsi ini bisa menghitung metrik dengan dua cara: memakai label asli (`y_true`), atau memakai error hasil perkiraan.
"""

import numpy as np
from sklearn.metrics import mean_absolute_error, mean_squared_error

def get_metrics(y_pred, y_true=None, error=None, abs_error=None, sq_error=None):
  # KASUS 1: label asli tersedia -> hitung MAE & MSE yang sebenarnya
  if y_true is not None:
    return pd.Series({
      'mae': mean_absolute_error(y_true, y_pred),
      'mse': mean_squared_error(y_true, y_pred)
    })
  # KASUS 2: label tidak tersedia -> hitung dari error hasil perkiraan
  else:
    # Jika error absolut tidak diberikan, buat dari |error|
    abs_error = abs_error if abs_error is not None else np.abs(error)
    # Jika error kuadrat tidak diberikan, buat dari error
    # CATATAN: di sini tertulis np.abs(error); seharusnya error ** 2.
    # Akibatnya "MSE" pendekatan naif (pred_e_mse) sebenarnya bernilai sama dengan MAE-nya.
    sq_error = sq_error if sq_error is not None else np.abs(error)
    return pd.Series({
      'mae': np.mean(abs_error),   # MAE = rata-rata error absolut
      'mse': np.mean(sq_error)     # MSE = rata-rata error kuadrat
    })

"""### Langkah 7 — Membandingkan metrik asli vs perkiraan di 10 kelompok data produksi
Data produksi diurutkan berdasarkan nilai prediksi, lalu dibagi menjadi **10 kelompok (fold)**. Untuk setiap fold dihitung:

| Kolom | Arti |
|---|---|
| `test_mae`, `test_mse` | Metrik di data test (garis acuan) |
| `true_mae`, `true_mse` | Metrik **sebenarnya** di produksi (pakai label) |
| `pred_e_mae`, `pred_e_mse` | Perkiraan dari **model error biasa** (naif) |
| `pred_se_mae`, `pred_se_mse` | Perkiraan dari **model error absolut/kuadrat** (DLE) |
"""

np.random.seed(123)  # agar urutan acak fold selalu sama

metrics_log = pd.DataFrame()  # tabel kosong untuk mencatat hasil tiap fold

# Metrik di data test (dihitung sekali, menjadi garis acuan)
metrics_test = get_metrics(y_true=y_test, y_pred=pred_test)

# - pred_prod.sort_values().index -> index data produksi diurutkan dari prediksi terkecil ke terbesar
# - np.array_split(..., 10)       -> dibagi menjadi 10 kelompok
# - np.random.permutation(...)    -> urutan ke-10 kelompok diacak
# - zip(..., range(10))           -> setiap kelompok (ix) diberi nomor fold i = 0..9
for ix, i in zip(
  np.random.permutation(np.array_split(pred_prod.sort_values().index, 10)),
  range(10)):

  # MAE & MSE SEBENARNYA (memakai label asli y_prod)
  metrics_true_prod = get_metrics(y_true=y_prod.loc[ix], y_pred=pred_prod.loc[ix])
  # MAE & MSE PERKIRAAN dari model error biasa (pendekatan naif)
  metrics_pred_error_prod = get_metrics(y_pred=pred_prod.loc[ix], error=pred_error_prod.loc[ix])
  # MAE & MSE PERKIRAAN dari model error absolut & kuadrat (pendekatan DLE)
  metrics_pred_serror_prod = get_metrics(y_pred=pred_prod.loc[ix], abs_error=pred_abs_error_prod.loc[ix], sq_error=pred_sq_error_prod.loc[ix])

  # Menyimpan semua hasil ke baris ke-i pada tabel metrics_log
  metrics_log.loc[i, ['test_mae', 'test_mse']] = metrics_test.loc[['mae', 'mse']].tolist()
  metrics_log.loc[i, ['true_mae', 'true_mse']] = metrics_true_prod.loc[['mae', 'mse']].tolist()
  metrics_log.loc[i, ['pred_e_mae', 'pred_e_mse']] = metrics_pred_error_prod.loc[['mae', 'mse']].tolist()
  metrics_log.loc[i, ['pred_se_mae', 'pred_se_mse']] = metrics_pred_serror_prod.loc[['mae', 'mse']].tolist()

"""## Hasil — Grafik Perbandingan
Cara membaca setiap grafik:
- **Abu-abu**: metrik di data test (acuan, konstan).
- **Biru**: metrik **sebenarnya** di produksi.
- **Merah**: metrik **perkiraan** (tanpa label).

👉 Semakin **dekat garis merah dengan garis biru**, semakin baik metode perkiraannya.

### Grafik 1 — MAE: asli vs perkiraan DLE (model error absolut)
"""

import matplotlib.pyplot as plt

f, ax = plt.subplots()

# Membandingkan MAE asli vs MAE perkiraan dari model error ABSOLUT (DLE)
ax.plot(metrics_log['test_mae'], label='Observed MAE\n(on Test Set)', lw=3, color='lightgrey')   # acuan dari data test
ax.plot(metrics_log['true_mae'], 'o-', label='Observed MAE\n(on Production Set)', lw=3, color='blue')   # nilai sebenarnya
ax.plot(metrics_log['pred_se_mae'], 'o-', label='Predicted MAE\n(on Production Set)', lw=3, color='red')   # nilai perkiraan

ax.set_xticks(range(10))                       # sumbu X: fold 0 sampai 9
ax.set_xlabel('Production fold', fontsize=14)

ax.xaxis.set_tick_params(labelsize=14)
ax.yaxis.set_tick_params(labelsize=14)
ax.legend(loc='center left', bbox_to_anchor=(1, 0.5), fontsize=14)   # legenda di sisi kanan grafik

f.savefig('mae_obs_vs_pred.png', dpi=200, bbox_inches='tight')

"""### Grafik 2 — MSE: asli vs perkiraan DLE (model error kuadrat)"""

f, ax = plt.subplots()

# Membandingkan MSE asli vs MSE perkiraan dari model error KUADRAT (DLE)
ax.plot(metrics_log['test_mse'], label='Observed MSE\n(on Test Set)', lw=3, color='lightgrey')   # acuan dari data test
ax.plot(metrics_log['true_mse'], 'o-', label='Observed MSE\n(on Production Set)', lw=3, color='blue')   # nilai sebenarnya
ax.plot(metrics_log['pred_se_mse'], 'o-', label='Predicted MSE\n(on Production Set)', lw=3, color='red')   # nilai perkiraan

ax.set_xticks(range(10))                       # sumbu X: fold 0 sampai 9
ax.set_xlabel('Production fold', fontsize=14)

ax.xaxis.set_tick_params(labelsize=14)
ax.yaxis.set_tick_params(labelsize=14)
ax.legend(loc='center left', bbox_to_anchor=(1, 0.5), fontsize=14)   # legenda di sisi kanan grafik

f.savefig('mse_obs_vs_pred.png', dpi=200, bbox_inches='tight')

"""### Grafik 3 — MAE: asli vs perkiraan naif (model error biasa)
Model yang menebak error bertanda (+/−) cenderung menghasilkan tebakan mendekati 0, karena error positif dan negatif saling meniadakan saat model belajar. Akibatnya MAE perkiraannya cenderung **terlalu kecil**.
"""

f, ax = plt.subplots()

# Membandingkan MAE asli vs MAE perkiraan dari model error BIASA (pendekatan naif)
ax.plot(metrics_log['test_mae'], label='Observed MAE\n(on Test Set)', lw=3, color='lightgrey')   # acuan dari data test
ax.plot(metrics_log['true_mae'], 'o-', label='Observed MAE\n(on Production Set)', lw=3, color='blue')   # nilai sebenarnya
ax.plot(metrics_log['pred_e_mae'], 'o-', label='Predicted MAE\n(on Production Set)', lw=3, color='red')   # nilai perkiraan

ax.set_xticks(range(10))                       # sumbu X: fold 0 sampai 9
ax.set_xlabel('Production fold', fontsize=14)

ax.xaxis.set_tick_params(labelsize=14)
ax.yaxis.set_tick_params(labelsize=14)
ax.legend(loc='center left', bbox_to_anchor=(1, 0.5), fontsize=14)   # legenda di sisi kanan grafik

f.savefig('mae_obs_vs_pred_se.png', dpi=200, bbox_inches='tight')

"""### Grafik 4 — MSE: asli vs perkiraan naif (model error biasa)
⚠️ Karena kekeliruan di fungsi `get_metrics`, nilai merah di grafik ini sebenarnya adalah MAE, bukan MSE.
"""

f, ax = plt.subplots()

# Membandingkan MSE asli vs MSE perkiraan dari model error BIASA (pendekatan naif)
ax.plot(metrics_log['test_mse'], label='Observed MSE\n(on Test Set)', lw=3, color='lightgrey')   # acuan dari data test
ax.plot(metrics_log['true_mse'], 'o-', label='Observed MSE\n(on Production Set)', lw=3, color='blue')   # nilai sebenarnya
ax.plot(metrics_log['pred_e_mse'], 'o-', label='Predicted MSE\n(on Production Set)', lw=3, color='red')   # nilai perkiraan

ax.set_xticks(range(10))                       # sumbu X: fold 0 sampai 9
ax.set_xlabel('Production fold', fontsize=14)

ax.xaxis.set_tick_params(labelsize=14)
ax.yaxis.set_tick_params(labelsize=14)
ax.legend(loc='center left', bbox_to_anchor=(1, 0.5), fontsize=14)   # legenda di sisi kanan grafik

f.savefig('mse_obs_vs_pred_se.png', dpi=200, bbox_inches='tight')

"""## Kesimpulan
1. Di produksi, label sering tidak tersedia, sehingga performa model tidak bisa dihitung langsung.
2. **Direct Loss Estimation** melatih model kedua untuk **langsung menebak besarnya error** (absolut atau kuadrat).
3. Menebak error biasa (bertanda +/−) lalu mengambil nilai absolutnya **tidak efektif**, karena tebakan cenderung mendekati nol.
4. Pendekatan DLE inilah yang dipakai library **NannyML** untuk memantau performa model regresi tanpa label.
"""